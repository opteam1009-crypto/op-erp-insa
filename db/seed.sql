-- 부서 마스터.
--
-- departments 테이블에는 parent_id가 없어 계층을 담지 못하므로 마케팅부와 그
-- 하위 네 팀을 같은 레벨로 넣는다. 사원은 어차피 말단 팀에 소속되므로 현재
-- 화면들에는 영향이 없다. 조직 단위 집계가 필요해지면 그때 parent_id를
-- 추가해도 기존 행은 깨지지 않는다.
--
-- 표기는 '콘텐츠'로 통일했다 (국립국어원 표기). 기존 인사대장에는 '영상컨텐츠'
-- 처럼 '컨텐츠'로 적힌 값이 있는데, name이 unique 키라 한 글자만 달라도
-- 엑셀 일괄 등록이 "알 수 없는 부서명"으로 실패한다.
insert into departments (name) values
  ('기획운영팀'),
  ('회계팀'),
  ('마케팅부'),
  ('콘텐츠팀'),
  ('퍼포먼스팀'),
  ('영상콘텐츠팀'),
  ('매장콘텐츠팀'),
  ('개발팀'),
  ('운영관리팀'),
  ('부동산팀')
on conflict (name) do nothing;
